#include "libft.h"

char	*ft_strdup(const char *str)
{
	char	*dest;
	size_t	len;
	size_t	i;

	len = ft_strlen(str);
	dest = malloc(sizeof(char) * (len + 1));
	if (!dest)
		return (NULL);
	i = 0;
	while (str[i])
	{
		dest[i] = str[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
